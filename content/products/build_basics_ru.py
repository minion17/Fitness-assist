def main() -> None:
    rows, names = [], set()
    for category, items in CATALOG.items():
        for name, kcal, p, f, c, *extra in items:
            assert name not in names, f"дубль: {name}"
            assert 0 <= p + f + c <= 100.5 and 0 <= kcal <= 900, name
            alcohol = category == "Напитки" and any(w in name for w in ("Вино", "Шампанское", "Коньяк", "Виски", "Пиво", "Сидр"))
            assert alcohol or abs(4 * p + 9 * f + 4 * c - kcal) <= max(40, kcal * 0.25) or kcal < 30, f"калории не сходятся: {name}"
            names.add(name)
            rows.append({"name": name, "kcal": kcal, "protein_g": p, "fat_g": f, "carbs_g": c, "category": category, **(extra[0] if extra else {})})
    (HERE / "basics_ru.json").write_text(json.dumps(rows, ensure_ascii=False, indent=1), encoding="utf-8")
