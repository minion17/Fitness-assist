test('hides empty actions and saves distinct planned weights', async () => {
  const save = vi.fn().mockResolvedValue(undefined)
  render(<ProgramBuilder exercises={[{id:1,name:'Приседания'}]} onSave={save} onCancel={() => {}} />)
  fireEvent.change(screen.getByLabelText('Название программы'),{target:{value:'Силовая'}})
  fireEvent.click(screen.getByRole('button',{name:'Продолжить'}))
  expect(screen.queryByRole('button',{name:'Сохранить программу'})).toBeNull()
  fireEvent.click(screen.getByRole('button',{name:'+ Добавить тренировку'}))
  expect(screen.queryByRole('button',{name:'Готово'})).toBeNull()
  fireEvent.click(screen.getByRole('button',{name:'Добавить упражнение'}))
  fireEvent.click(screen.getByText('Указать вес по подходам'))
  fireEvent.change(screen.getByLabelText('Упражнение 1, вес подхода 1'),{target:{value:'20'}})
  fireEvent.change(screen.getByLabelText('Упражнение 1, вес подхода 2'),{target:{value:'25'}})
  fireEvent.click(screen.getByRole('button',{name:'Добавить'}))
  fireEvent.click(screen.getByRole('button',{name:'Готово'}))
  expect(screen.getByText(/вес: 20 \/ 25 \/ — кг/)).toBeTruthy()
  fireEvent.click(screen.getByRole('button',{name:'Сохранить'}))
  fireEvent.click(screen.getByRole('button',{name:'Сохранить программу'}))
  await waitFor(() => expect(save).toHaveBeenCalledOnce())
  expect(save.mock.calls[0][0].days[0].exercises[0].planned_weights).toEqual([20,25,null])
})


