import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, expect, test, vi } from 'vitest'
import { cleanup } from '@testing-library/react'
import ProgramBuilder from './ProgramBuilder'

afterEach(cleanup)
test('uses one field to find and select an exercise', async () => {
  const save = vi.fn().mockResolvedValue(undefined)
  render(<ProgramBuilder exercises={[{ id: 1, name: 'Планка' }, { id: 2, name: 'Приседания' }]} onSave={save} onCancel={() => {}} />)
  fireEvent.change(screen.getByLabelText('Название программы'), { target: { value: 'Моя программа' } })
  fireEvent.click(screen.getByRole('button', { name: 'Продолжить' }))
  fireEvent.click(screen.getByRole('button', { name: '+ Добавить тренировку' }))
  fireEvent.click(screen.getByRole('button', { name: 'Добавить упражнение' }))
  expect(screen.queryByLabelText('Поиск упражнения 1')).toBeNull()
  fireEvent.change(screen.getByLabelText('Упражнение 1'), { target: { value: 'присед' } })
  fireEvent.click(screen.getByRole('button', { name: 'Приседания' }))
  fireEvent.click(screen.getByRole('button', { name: 'Добавить' }))
  fireEvent.click(screen.getByRole('button', { name: 'Готово' }))
  fireEvent.click(screen.getByRole('button', { name: 'Сохранить' }))
  fireEvent.click(screen.getByRole('button', { name: 'Сохранить программу' }))
  await waitFor(() => expect(save).toHaveBeenCalled())
  expect(save.mock.calls[0][0].days[0].exercises[0].exercise_id).toBe(2)
})
