test('creates a superset and saves an exercise in seconds', async () => {
  const save = vi.fn().mockResolvedValue(undefined)
  render(<ProgramBuilder exercises={[{ id: 1, name: 'Планка' }, { id: 2, name: 'Гиря' }]} onSave={save} onCancel={() => {}} />)
  fireEvent.change(screen.getByLabelText('Название программы'), { target: { value: 'Силовая' } })
  fireEvent.click(screen.getByRole('button', { name: 'Продолжить' }))
  fireEvent.click(screen.getByRole('button', { name: '+ Добавить тренировку' }))
  fireEvent.click(screen.getByRole('button', { name: 'Добавить суперсет' }))
  expect(screen.getByText('Суперсет 1 · Упражнение 1')).toBeTruthy()
  expect(screen.getByText('Суперсет 1 · Упражнение 2')).toBeTruthy()
  fireEvent.change(screen.getByLabelText('Тип нагрузки 1'), { target: { value: 'seconds' } })
  fireEvent.change(screen.getByLabelText('Время 1'), { target: { value: '45' } })
  fireEvent.change(screen.getByLabelText('Упражнение 2'), { target: { value: 'Гиря' } })
  fireEvent.click(screen.getByRole('button', { name: 'Гиря' }))
  fireEvent.click(screen.getByRole('button', { name: 'Добавить' }))
  fireEvent.click(screen.getByRole('button', { name: 'Готово' }))
  fireEvent.click(screen.getByRole('button', { name: 'Сохранить' }))
  fireEvent.click(screen.getByRole('button', { name: 'Сохранить программу' }))
  await waitFor(() => expect(save).toHaveBeenCalled())
  const items = save.mock.calls[0][0].days[0].exercises
  expect(items.map((item: { superset: number }) => item.superset)).toEqual([1, 1])
  expect(items[0].unit).toBe('seconds')
  expect(items[0].reps).toBe('45')
  expect(items[1].exercise_id).toBe(2)
})

